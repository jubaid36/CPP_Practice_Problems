#include<bits/stdc++.h> // এই হেডার ফাইল সব স্ট্যান্ডার্ড লাইব্রেরি ইনক্লুড করে
using namespace std;

int main()
{
    int n;

    // ইউজার থেকে ইনপুট নেয়া হচ্ছে
    cout << "Input the N: ";
    cin >> n;

    // বিজোড় সংখ্যা প্রিন্ট করার জন্য লুপ
    for(int i = 1; i <= n; i += 2) // i এর শুরু 1 থেকে, প্রতি ধাপে 2 করে বাড়ছে (1, 3, 5, ...)
    {
        cout << "Odd Numbers: " << i << endl; // প্রতি বিজোড় সংখ্যা প্রিন্ট হচ্ছে
    }

    cout << endl; // নতুন লাইনের জন্য (output সুন্দরভাবে আলাদা করার জন্য)

    // জোড় সংখ্যা প্রিন্ট করার জন্য লুপ
    for(int i = 0; i <= n; i += 2) // i এর শুরু 0 থেকে, প্রতি ধাপে 2 করে বাড়ছে (0, 2, 4, ...)
    {
        cout << "Even Numbers: " << i << endl; // প্রতি জোড় সংখ্যা প্রিন্ট হচ্ছে
    }

    return 0; // প্রোগ্রাম সফলভাবে শেষ
}
