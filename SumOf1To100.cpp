#include<bits/stdc++.h> // সব ধরনের স্ট্যান্ডার্ড লাইব্রেরি একসাথে ইনক্লুড করে
using namespace std;

int main()
{
    int sum = 0; // sum নামক একটি ভেরিয়েবল তৈরি করা হয়েছে, যেটাতে যোগফল রাখা হবে

    // 1 থেকে 100 পর্যন্ত সব সংখ্যা লুপের মাধ্যমে যোগ করা হচ্ছে
    for(int i = 1; i <= 100; i++) // i শুরু 1 থেকে, প্রতি ধাপে 1 করে বাড়বে, যতক্ষণ না i > 100
    {
        sum += i; // sum = sum + i → প্রতিবার বর্তমান সংখ্যাটি যোগ হচ্ছে
    }

    // যোগফল প্রিন্ট করা হচ্ছে
    cout << "The sum of the numbers from 1 to 100 = " << sum << endl;

    return 0; // প্রোগ্রাম সফলভাবে শেষ
}
